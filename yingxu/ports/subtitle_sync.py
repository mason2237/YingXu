from typing import Protocol


class SubtitleSyncEngine(Protocol):
    def available(self)->bool: ...
    def align(self,source,reference,*,should_stop=None,**options)->dict: ...


class TransformArtifacts(Protocol):
    def create(self,filename,text,metadata)->dict: ...
    def get(self,identifier)->dict: ...
    def path(self,identifier): ...
    def list(self)->list: ...

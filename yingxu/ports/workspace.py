"""External capabilities needed by workspace use cases."""
from pathlib import Path
from typing import Protocol


class Filesystem(Protocol):
    def collect(self, folder: Path, recursive: bool, **options): ...
    def exists(self, path: Path) -> bool: ...
    def inside(self, path: Path, root: Path) -> bool: ...
    def directory_mark(self, folder: Path): ...
    def file_mark(self, path: Path): ...
    def fingerprint(self, path: Path) -> dict: ...


class MediaInspector(Protocol):
    def inspect(self, videos, options, filesystem, stop, report) -> dict: ...


class Previewer(Protocol):
    def freeze(self, review): ...


class HistoryReader(Protocol):
    def recent(self, limit: int) -> list[dict]: ...


class Settings(Protocol):
    def read(self) -> dict: ...
    def write(self, value: dict) -> None: ...

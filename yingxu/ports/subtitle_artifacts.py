"""Private transfer buffers. IDs cross the UI boundary; paths never do."""
from typing import Protocol


class SubtitleArtifacts(Protocol):
    root: object
    def reserve(self, offer: dict, association: dict) -> dict: ...
    def get(self, identifier: str) -> dict: ...
    def update(self, identifier: str, **changes) -> dict: ...
    def list(self) -> list[dict]: ...
    def transfer(self, identifier, stop, report, headers=None): ...
    def prepare(self, identifier, stop): ...
    def prepared(self, identifier) -> list: ...
    def discard(self, identifier, protected): ...
    def path(self, identifier): ...
    def maintenance_due(self) -> bool: ...
    def compact(self, identifier, protected, stop): ...
    def maintain(self, protected, stop): ...

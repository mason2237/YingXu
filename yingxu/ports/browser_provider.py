"""Browser-assisted provider. Plans originate from trusted Python adapters."""
from typing import Protocol


class BrowserProvider(Protocol):
    def plan(self, query: str, provider: str) -> dict: ...
    def results(self, raw: str, provider: str, video_name: str, language: str) -> tuple[str, list[dict]]: ...
    def url(self, candidate: dict, provider: str) -> str: ...
    def download(self, candidate: dict, provider: str) -> str | None: ...
